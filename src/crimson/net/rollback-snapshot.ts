function mapMoveToEnd<K, V>(map: Map<K, V>, key: K, last = true): void {
  if (!map.has(key)) {
    return;
  }
  const value = map.get(key)!;
  map.delete(key);
  if (last) {
    map.set(key, value);
    return;
  }
  const entries = Array.from(map.entries());
  map.clear();
  map.set(key, value);
  for (const [entryKey, entryValue] of entries) {
    map.set(entryKey, entryValue);
  }
}

class MsgpackEncoder {
  private readonly _encoder = new TextEncoder();
  private _bytes: number[] = [];

  encode(value: unknown): Uint8Array {
    this._bytes = [];
    this.writeValue(value);
    return new Uint8Array(this._bytes);
  }

  private writeValue(value: unknown): void {
    if (value === null || value === undefined) {
      this.writeByte(0xc0);
    } else if (typeof value === 'boolean') {
      this.writeByte(value ? 0xc3 : 0xc2);
    } else if (typeof value === 'number') {
      this.writeNumber(value);
    } else if (typeof value === 'string') {
      this.writeString(value);
    } else if (value instanceof Uint8Array) {
      this.writeBinary(value);
    } else if (ArrayBuffer.isView(value)) {
      const view = value as ArrayBufferView;
      this.writeBinary(new Uint8Array(view.buffer, view.byteOffset, view.byteLength));
    } else if (Array.isArray(value)) {
      this.writeArray(value);
    } else if (value instanceof Map) {
      this.writeMap(Array.from(value.entries()));
    } else if (typeof value === 'object') {
      this.writeObject(value as Record<string, unknown>);
    } else {
      throw new Error('unsupported msgpack value');
    }
  }

  private writeNumber(value: number): void {
    if (!Number.isFinite(value) || !Number.isInteger(value)) {
      this.writeByte(0xcb);
      const buffer = new ArrayBuffer(8);
      new DataView(buffer).setFloat64(0, value, false);
      this.writeBytes(new Uint8Array(buffer));
    } else if (value >= 0 && value <= 0x7f) {
      this.writeByte(value);
    } else if (value >= -32 && value < 0) {
      this.writeByte(0x100 + value);
    } else if (value >= 0 && value <= 0xff) {
      this.writeByte(0xcc);
      this.writeByte(value);
    } else if (value >= 0 && value <= 0xffff) {
      this.writeByte(0xcd);
      this.writeUint16(value);
    } else if (value >= 0 && value <= 0xffffffff) {
      this.writeByte(0xce);
      this.writeUint32(value);
    } else if (value >= -0x80 && value < 0) {
      this.writeByte(0xd0);
      this.writeByte(value);
    } else if (value >= -0x8000 && value < 0) {
      this.writeByte(0xd1);
      this.writeUint16(value);
    } else if (value >= -0x80000000 && value < 0) {
      this.writeByte(0xd2);
      this.writeUint32(value);
    } else {
      this.writeByte(0xcb);
      const buffer = new ArrayBuffer(8);
      new DataView(buffer).setFloat64(0, value, false);
      this.writeBytes(new Uint8Array(buffer));
    }
  }

  private writeString(value: string): void {
    const bytes = this._encoder.encode(value);
    if (bytes.length <= 31) {
      this.writeByte(0xa0 | bytes.length);
    } else if (bytes.length <= 0xff) {
      this.writeByte(0xd9);
      this.writeByte(bytes.length);
    } else if (bytes.length <= 0xffff) {
      this.writeByte(0xda);
      this.writeUint16(bytes.length);
    } else {
      this.writeByte(0xdb);
      this.writeUint32(bytes.length);
    }
    this.writeBytes(bytes);
  }

  private writeBinary(value: Uint8Array): void {
    if (value.length <= 0xff) {
      this.writeByte(0xc4);
      this.writeByte(value.length);
    } else if (value.length <= 0xffff) {
      this.writeByte(0xc5);
      this.writeUint16(value.length);
    } else {
      this.writeByte(0xc6);
      this.writeUint32(value.length);
    }
    this.writeBytes(value);
  }

  private writeArray(value: readonly unknown[]): void {
    if (value.length <= 15) {
      this.writeByte(0x90 | value.length);
    } else if (value.length <= 0xffff) {
      this.writeByte(0xdc);
      this.writeUint16(value.length);
    } else {
      this.writeByte(0xdd);
      this.writeUint32(value.length);
    }
    for (const item of value) {
      this.writeValue(item);
    }
  }

  private writeObject(value: Record<string, unknown>): void {
    const entries = Object.keys(value)
      .filter((key) => value[key] !== undefined)
      .map((key): [string, unknown] => [key, value[key]]);
    this.writeMap(entries);
  }

  private writeMap(entries: readonly (readonly [unknown, unknown])[]): void {
    if (entries.length <= 15) {
      this.writeByte(0x80 | entries.length);
    } else if (entries.length <= 0xffff) {
      this.writeByte(0xde);
      this.writeUint16(entries.length);
    } else {
      this.writeByte(0xdf);
      this.writeUint32(entries.length);
    }
    for (const [key, value] of entries) {
      this.writeValue(key);
      this.writeValue(value);
    }
  }

  private writeByte(value: number): void {
    this._bytes.push(value & 0xff);
  }

  private writeBytes(value: Uint8Array): void {
    for (const byte of value) {
      this.writeByte(byte);
    }
  }

  private writeUint16(value: number): void {
    this.writeByte(value >> 8);
    this.writeByte(value);
  }

  private writeUint32(value: number): void {
    this.writeByte(value / 0x1000000);
    this.writeByte(value >> 16);
    this.writeByte(value >> 8);
    this.writeByte(value);
  }
}

class MsgpackDecoder<T> {
  private readonly _type?: new (...args: any[]) => T;

  constructor(opts: { type?: new (...args: any[]) => T } = {}) {
    this._type = opts.type;
  }

  decode(blob: Uint8Array): T {
    const value = new MsgpackReader(blob).read();
    if (
      this._type !== undefined
      && value !== null
      && typeof value === 'object'
      && !Array.isArray(value)
      && !(value instanceof Uint8Array)
      && !(value instanceof Map)
    ) {
      return new this._type(value);
    }
    return value as T;
  }
}

class MsgpackReader {
  private readonly _decoder = new TextDecoder();
  private _offset = 0;

  constructor(private readonly _data: Uint8Array) {}

  read(): unknown {
    const value = this.readValue();
    if (this._offset !== this._data.length) {
      throw new Error('trailing msgpack bytes');
    }
    return value;
  }

  private readValue(): unknown {
    const tag = this.readByte();
    if (tag <= 0x7f) {
      return tag;
    }
    if (tag >= 0xe0) {
      return tag - 0x100;
    }
    if (tag >= 0xa0 && tag <= 0xbf) {
      return this.readString(tag & 0x1f);
    }
    if (tag >= 0x90 && tag <= 0x9f) {
      return this.readArray(tag & 0x0f);
    }
    if (tag >= 0x80 && tag <= 0x8f) {
      return this.readMap(tag & 0x0f);
    }
    switch (tag) {
      case 0xc0:
        return null;
      case 0xc2:
        return false;
      case 0xc3:
        return true;
      case 0xc4:
        return this.readBytes(this.readByte());
      case 0xc5:
        return this.readBytes(this.readUint16());
      case 0xc6:
        return this.readBytes(this.readUint32());
      case 0xcb:
        return this.readFloat64();
      case 0xcc:
        return this.readByte();
      case 0xcd:
        return this.readUint16();
      case 0xce:
        return this.readUint32();
      case 0xd0:
        return this.toSigned(this.readByte(), 0x80, 0x100);
      case 0xd1:
        return this.toSigned(this.readUint16(), 0x8000, 0x10000);
      case 0xd2:
        return this.toSigned(this.readUint32(), 0x80000000, 0x100000000);
      case 0xd9:
        return this.readString(this.readByte());
      case 0xda:
        return this.readString(this.readUint16());
      case 0xdb:
        return this.readString(this.readUint32());
      case 0xdc:
        return this.readArray(this.readUint16());
      case 0xdd:
        return this.readArray(this.readUint32());
      case 0xde:
        return this.readMap(this.readUint16());
      case 0xdf:
        return this.readMap(this.readUint32());
      default:
        throw new Error('unsupported msgpack tag: ' + tag);
    }
  }

  private readArray(length: number): unknown[] {
    const result: unknown[] = [];
    for (let index = 0; index < length; index += 1) {
      result.push(this.readValue());
    }
    return result;
  }

  private readMap(length: number): Record<string, unknown> | Map<unknown, unknown> {
    const entries: [unknown, unknown][] = [];
    let stringKeys = true;
    for (let index = 0; index < length; index += 1) {
      const key = this.readValue();
      const value = this.readValue();
      entries.push([key, value]);
      stringKeys = stringKeys && typeof key === 'string';
    }
    if (!stringKeys) {
      return new Map(entries);
    }
    const result: Record<string, unknown> = {};
    for (const [key, value] of entries) {
      result[key as string] = value;
    }
    return result;
  }

  private readString(length: number): string {
    return this._decoder.decode(this.readBytes(length));
  }

  private readFloat64(): number {
    const bytes = this.readBytes(8);
    return new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getFloat64(0, false);
  }

  private readUint16(): number {
    return (this.readByte() << 8) | this.readByte();
  }

  private readUint32(): number {
    return (this.readByte() * 0x1000000) + (this.readByte() << 16) + (this.readByte() << 8) + this.readByte();
  }

  private readByte(): number {
    if (this._offset >= this._data.length) {
      throw new Error('unexpected end of msgpack data');
    }
    const byte = this._data[this._offset];
    this._offset += 1;
    return byte;
  }

  private readBytes(length: number): Uint8Array {
    if (this._offset + length > this._data.length) {
      throw new Error('unexpected end of msgpack data');
    }
    const bytes = this._data.slice(this._offset, this._offset + length);
    this._offset += length;
    return bytes;
  }

  private toSigned(value: number, signBit: number, range: number): number {
    return value >= signBit ? value - range : value;
  }
}

// Serialize rollback snapshots as deterministic msgpack blobs.
export class RollbackSnapshotCodec<SnapshotT> {
  snapshotType: new (...args: any[]) => SnapshotT;
  _encoder: MsgpackEncoder;
  _decoder: MsgpackDecoder<any>;

  constructor(opts: {
    snapshotType: new (...args: any[]) => SnapshotT;
    _encoder?: MsgpackEncoder;
    _decoder?: MsgpackDecoder<any>;
  }) {
    this.snapshotType = opts.snapshotType;
    this._encoder = new MsgpackEncoder();
    this._decoder = new MsgpackDecoder({ type: this.snapshotType });
  }

  dumps(snapshot: SnapshotT): Uint8Array {
    return this._encoder.encode(snapshot);
  }

  loads(blob: Uint8Array): SnapshotT {
    return this._decoder.decode(blob);
  }
}

// Store periodic snapshots for rollback and reconnect restore.
export class RollbackSnapshotRing<SnapshotT> {
  maxTicks: number;
  codec: RollbackSnapshotCodec<SnapshotT>;
  intervalTicks: number;
  _byTick: Map<number, Uint8Array>;

  constructor(opts: {
    maxTicks: number;
    codec: RollbackSnapshotCodec<SnapshotT>;
    intervalTicks?: number;
    _byTick?: Map<number, Uint8Array>;
  }) {
    this.maxTicks = opts.maxTicks;
    this.codec = opts.codec;
    this.intervalTicks = opts.intervalTicks ?? 4;
    this._byTick = opts._byTick ?? new Map();
  }

  clear(): void {
    this._byTick.clear();
  }

  maybeStore(opts: { tickIndex: number; snapshot: SnapshotT; force?: boolean }): boolean {
    const tickIndex = opts.tickIndex;
    const snapshot = opts.snapshot;
    const force = opts.force ?? false;
    const tick = Math.trunc(tickIndex);
    if (tick < 0) {
      return false;
    }
    const interval = Math.max(1, Math.trunc(this.intervalTicks));
    if (!force && (tick % interval) !== 0) {
      return false;
    }
    this._byTick.set(tick, this.codec.dumps(snapshot));
    mapMoveToEnd(this._byTick, tick, true);
    this._prune({ maxTick: tick });
    return true;
  }

  hasTick(tickIndex: number): boolean {
    return this._byTick.has(Math.trunc(tickIndex));
  }

  restoreExact(tickIndex: number): SnapshotT | null {
    const blob = this._byTick.get(Math.trunc(tickIndex)) ?? null;
    if (blob === null) {
      return null;
    }
    return this.codec.loads(blob);
  }

  restoreLatestAtOrBefore(tickIndex: number): [number, SnapshotT] | null {
    const target = Math.trunc(tickIndex);
    let candidate: number | null = null;
    for (const tick of this._byTick.keys()) {
      if (Math.trunc(tick) <= Math.trunc(target)) {
        candidate = Math.trunc(tick);
      } else {
        break;
      }
    }
    if (candidate === null) {
      return null;
    }
    const blob = this._byTick.get(Math.trunc(candidate)) ?? null;
    if (blob === null) {
      return null;
    }
    return [Math.trunc(candidate), this.codec.loads(blob)];
  }

  _prune(opts: { maxTick: number }): void {
    const maxTick = opts.maxTick;
    const keepFrom = Math.trunc(maxTick) - Math.max(1, Math.trunc(this.maxTicks));
    for (const tick of Array.from(this._byTick.keys())) {
      if (Math.trunc(tick) >= Math.trunc(keepFrom)) {
        continue;
      }
      this._byTick.delete(Math.trunc(tick));
    }
  }
}
